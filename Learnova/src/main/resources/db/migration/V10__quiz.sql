-- Starts a regular quiz attempt for an enrollment. Enforces the daily
-- attempt limit and snapshots the drawn questions.
CREATE OR REPLACE FUNCTION public.sp_start_quiz_attempt(
    p_enrollment_id BIGINT,
    p_quiz_id       BIGINT
)
RETURNS TABLE (
    attempt_id     BIGINT,
    quiz_id        BIGINT,
    enrollment_id  BIGINT,
    attempt_no     INTEGER,
    started_at     TIMESTAMPTZ
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_attempt_no        INTEGER;
    v_questions_per     INTEGER;
    v_today_attempts    INTEGER;
    v_enrollment_status VARCHAR(20);
BEGIN
    SELECT e.status
    INTO v_enrollment_status
    FROM public.enrollments e
    WHERE e.id = p_enrollment_id;

    IF v_enrollment_status IS NULL THEN
        RAISE EXCEPTION 'LTQ01: Enrollment % does not exist.', p_enrollment_id
            USING ERRCODE = 'LTQ01';
    END IF;

    IF v_enrollment_status <> 'active' THEN
        RAISE EXCEPTION 'LTQ02: Only active enrollments can take quizzes.'
            USING ERRCODE = 'LTQ02';
    END IF;

    SELECT q.questions_per_attempt
    INTO v_questions_per
    FROM public.quizzes q
    WHERE q.id = p_quiz_id;

    IF v_questions_per IS NULL THEN
        RAISE EXCEPTION 'LTQ03: Quiz % does not exist.', p_quiz_id
            USING ERRCODE = 'LTQ03';
    END IF;

    SELECT COUNT(*)
    INTO v_today_attempts
    FROM public.quiz_attempts
    WHERE enrollment_id = p_enrollment_id
      AND quiz_id = p_quiz_id
      AND attempt_date = CURRENT_DATE;

    SELECT COALESCE(MAX(attempt_no), 0) + 1
    INTO v_attempt_no
    FROM public.quiz_attempts
    WHERE enrollment_id = p_enrollment_id
      AND quiz_id = p_quiz_id
      AND attempt_date = CURRENT_DATE;

    IF v_today_attempts >= (
        SELECT daily_attempt_limit
        FROM public.quizzes
        WHERE id = p_quiz_id
    ) THEN
        RAISE EXCEPTION 'LTQ04: Daily attempt limit for this quiz was reached.'
            USING ERRCODE = 'LTQ04';
    END IF;

    INSERT INTO public.quiz_attempts (enrollment_id, quiz_id, attempt_date, attempt_no)
    VALUES (p_enrollment_id, p_quiz_id, CURRENT_DATE, v_attempt_no)
    RETURNING
        public.quiz_attempts.id,
        public.quiz_attempts.quiz_id,
        public.quiz_attempts.enrollment_id,
        public.quiz_attempts.attempt_no,
        public.quiz_attempts.started_at
    INTO attempt_id, quiz_id, enrollment_id, attempt_no, started_at;

    INSERT INTO public.quiz_attempt_questions (attempt_id, question_id)
    SELECT attempt_id, qq.question_id
    FROM public.fn_quiz_pick_questions(p_quiz_id, v_questions_per) qq;

    RETURN NEXT;
    RETURN;

EXCEPTION
    WHEN OTHERS THEN
        IF SQLSTATE IN ('LTQ01', 'LTQ02', 'LTQ03', 'LTQ04') THEN
            RAISE;
        END IF;
        RAISE LOG 'sp_start_quiz_attempt unexpected sqlstate=%: %', SQLSTATE, SQLERRM;
        RAISE EXCEPTION 'LT500: Unexpected database error while starting the quiz: %', SQLERRM
            USING ERRCODE = 'LT500';
END;
$$;

-- Starts a bypass attempt: passing the quiz of a prerequisite course
-- to unlock a target course without completing the prerequisite.
CREATE OR REPLACE FUNCTION public.sp_start_bypass_attempt(
    p_user_id                BIGINT,
    p_target_course_id       BIGINT,
    p_prerequisite_course_id BIGINT
)
RETURNS TABLE (
    attempt_id             BIGINT,
    target_course_id       BIGINT,
    prerequisite_course_id BIGINT,
    attempt_no             INTEGER,
    started_at             TIMESTAMPTZ
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_attempt_no     INTEGER;
    v_quiz_id        BIGINT;
    v_questions_per  INTEGER;
    v_is_prerequisite BOOLEAN;
BEGIN
    SELECT EXISTS (
        SELECT 1
        FROM public.course_prerequisites
        WHERE course_id = p_target_course_id
          AND prerequisite_course_id = p_prerequisite_course_id
    )
    INTO v_is_prerequisite;

    IF NOT v_is_prerequisite THEN
        RAISE EXCEPTION 'LTP01: Course % is not a prerequisite of course %.',
            p_prerequisite_course_id, p_target_course_id
            USING ERRCODE = 'LTP01';
    END IF;

    -- Bypass quizzes use a quiz from the prerequisite course.
    SELECT q.id, q.questions_per_attempt
    INTO v_quiz_id, v_questions_per
    FROM public.quizzes q
    JOIN public.lessons l ON l.id = q.lesson_id
    WHERE l.course_id = p_prerequisite_course_id
    ORDER BY l.sequence_order ASC, q.id ASC
    LIMIT 1;

    IF v_quiz_id IS NULL THEN
        RAISE EXCEPTION 'LTQ03: Prerequisite course % has no quiz to bypass with.',
            p_prerequisite_course_id
            USING ERRCODE = 'LTQ03';
    END IF;

    SELECT COALESCE(MAX(attempt_no), 0) + 1
    INTO v_attempt_no
    FROM public.bypass_attempts
    WHERE user_id = p_user_id
      AND target_course_id = p_target_course_id
      AND prerequisite_course_id = p_prerequisite_course_id
      AND attempt_date = CURRENT_DATE;

    INSERT INTO public.bypass_attempts (
        user_id,
        target_course_id,
        prerequisite_course_id,
        attempt_date,
        attempt_no
    )
    VALUES (
        p_user_id,
        p_target_course_id,
        p_prerequisite_course_id,
        CURRENT_DATE,
        v_attempt_no
    )
    RETURNING
        public.bypass_attempts.id,
        public.bypass_attempts.target_course_id,
        public.bypass_attempts.prerequisite_course_id,
        public.bypass_attempts.attempt_no,
        public.bypass_attempts.started_at
    INTO attempt_id, target_course_id, prerequisite_course_id, attempt_no, started_at;

    INSERT INTO public.bypass_attempt_questions (attempt_id, source_question_id)
    SELECT attempt_id, qq.question_id
    FROM public.fn_quiz_pick_questions(v_quiz_id, v_questions_per) qq;

    RETURN NEXT;
    RETURN;

EXCEPTION
    WHEN OTHERS THEN
        IF SQLSTATE IN ('LTP01', 'LTQ03') THEN
            RAISE;
        END IF;
        RAISE LOG 'sp_start_bypass_attempt unexpected sqlstate=%: %', SQLSTATE, SQLERRM;
        RAISE EXCEPTION 'LT500: Unexpected database error while starting the bypass quiz: %', SQLERRM
            USING ERRCODE = 'LT500';
END;
$$;

-- Grades a submitted attempt. Correct answers are recorded on the
-- attempt_answers / bypass_attempt_answers rows; the grade is the share
-- of correctly answered questions among the snapshot.
--
--   regular attempt (p_bypass_quiz = FALSE):
--     * writes quiz_submissions history
--     * keeps the best score on enrollments.final_score_pct
--   bypass attempt (p_bypass_quiz = TRUE):
--     * a passing score (>= 60%) inserts a course_bypasses row, which
--       satisfies the prerequisite (V9) and fires the V9 unlock trigger
CREATE OR REPLACE FUNCTION public.sp_submit_quiz_attempt(
    p_attempt_id  BIGINT,
    p_bypass_quiz BOOLEAN
)
RETURNS TABLE (
    attempt_id BIGINT,
    status     VARCHAR(20),
    score_pct  NUMERIC(5,2),
    passed     BOOLEAN,
    submitted_at TIMESTAMPTZ
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_total       INTEGER;
    v_correct     INTEGER;
    v_score       NUMERIC(5,2);
    v_passed      BOOLEAN;
    v_passing     NUMERIC(5,2) := 60.00;
    v_user_id     BIGINT;
    v_target      BIGINT;
    v_prereq      BIGINT;
    v_enrollment  BIGINT;
BEGIN
    IF p_bypass_quiz THEN
        SELECT ba.id, ba.user_id, ba.target_course_id, ba.prerequisite_course_id, ba.status
        INTO attempt_id, v_user_id, v_target, v_prereq, status
        FROM public.bypass_attempts ba
        WHERE ba.id = p_attempt_id;
    ELSE
        SELECT qa.id, qa.enrollment_id, qa.status
        INTO attempt_id, v_enrollment, status
        FROM public.quiz_attempts qa
        WHERE qa.id = p_attempt_id;
    END IF;

    IF attempt_id IS NULL THEN
        RAISE EXCEPTION 'LTQ01: Attempt % does not exist.', p_attempt_id
            USING ERRCODE = 'LTQ01';
    END IF;

    IF status = 'submitted' THEN
        RAISE EXCEPTION 'LTQ05: Attempt % was already submitted.', p_attempt_id
            USING ERRCODE = 'LTQ05';
    END IF;

    IF p_bypass_quiz THEN
        SELECT COUNT(*),
               COUNT(*) FILTER (WHERE aa.is_correct)
        INTO v_total, v_correct
        FROM public.bypass_attempt_questions baq
        LEFT JOIN public.bypass_attempt_answers aa
               ON aa.attempt_id = baq.attempt_id
              AND aa.source_question_id = baq.source_question_id
        WHERE baq.attempt_id = p_attempt_id;
    ELSE
        SELECT COUNT(*),
               COUNT(*) FILTER (WHERE aa.is_correct)
        INTO v_total, v_correct
        FROM public.quiz_attempt_questions qaq
        LEFT JOIN public.attempt_answers aa
               ON aa.attempt_id = qaq.attempt_id
              AND aa.question_id = qaq.question_id
        WHERE qaq.attempt_id = p_attempt_id;
    END IF;

    IF v_total IS NULL OR v_total = 0 THEN
        RAISE EXCEPTION 'LTQ06: Attempt % has no answered questions.', p_attempt_id
            USING ERRCODE = 'LTQ06';
    END IF;

    v_score := ROUND((v_correct::NUMERIC / v_total::NUMERIC) * 100, 2);

    IF p_bypass_quiz THEN
        -- Bypass quizzes always pass at the standard 60% threshold.
        v_passed := v_score >= v_passing;
    ELSE
        SELECT q.passing_score
        INTO v_passing
        FROM public.quizzes q
        JOIN public.quiz_attempts qa ON qa.quiz_id = q.id
        WHERE qa.id = p_attempt_id;

        v_passed := v_score >= COALESCE(v_passing, 60.00);
    END IF;

    IF p_bypass_quiz THEN
        UPDATE public.bypass_attempts
        SET status = 'submitted',
            submitted_at = CURRENT_TIMESTAMP,
            score_pct = v_score,
            passed = v_passed
        WHERE id = p_attempt_id;

        IF v_passed THEN
            INSERT INTO public.course_bypasses (user_id, target_course_id, prerequisite_course_id)
            VALUES (v_user_id, v_target, v_prereq)
            ON CONFLICT (user_id, target_course_id, prerequisite_course_id) DO NOTHING;
        END IF;
    ELSE
        UPDATE public.quiz_attempts
        SET status = 'submitted',
            submitted_at = CURRENT_TIMESTAMP,
            score_pct = v_score,
            passed = v_passed
        WHERE id = p_attempt_id;

        INSERT INTO public.quiz_submissions (user_id, quiz_id, score_pct, passed)
        SELECT e.user_id, qa.quiz_id, v_score, v_passed
        FROM public.quiz_attempts qa
        JOIN public.enrollments e ON e.id = qa.enrollment_id
        WHERE qa.id = p_attempt_id;

        -- Keep the best score as the enrollment's final score.
        UPDATE public.enrollments e
        SET final_score_pct = GREATEST(
                COALESCE(e.final_score_pct, v_score),
                v_score
            )
        FROM public.quiz_attempts qa
        WHERE qa.id = p_attempt_id
          AND e.id = qa.enrollment_id;
    END IF;

    score_pct := v_score;
    passed := v_passed;
    submitted_at := CURRENT_TIMESTAMP;
    status := 'submitted';
    RETURN NEXT;
    RETURN;

EXCEPTION
    WHEN OTHERS THEN
        IF SQLSTATE IN ('LTQ01', 'LTQ05', 'LTQ06') THEN
            RAISE;
        END IF;
        RAISE LOG 'sp_submit_quiz_attempt unexpected sqlstate=%: %', SQLSTATE, SQLERRM;
        RAISE EXCEPTION 'LT500: Unexpected database error while submitting the quiz: %', SQLERRM
            USING ERRCODE = 'LT500';
END;
$$;

-- Records the option a student picked for one question of an attempt.
CREATE OR REPLACE FUNCTION public.sp_answer_quiz_question(
    p_attempt_id         BIGINT,
    p_question_id        BIGINT,
    p_selected_option_id BIGINT,
    p_bypass_quiz        BOOLEAN
)
RETURNS TABLE (
    attempt_id  BIGINT,
    question_id BIGINT,
    is_correct  BOOLEAN
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_correct BOOLEAN;
BEGIN
    SELECT qo.is_correct
    INTO v_correct
    FROM public.quiz_options qo
    WHERE qo.id = p_selected_option_id
      AND qo.question_id = p_question_id;

    IF v_correct IS NULL THEN
        RAISE EXCEPTION 'LTQ07: Option % does not belong to question %.',
            p_selected_option_id, p_question_id
            USING ERRCODE = 'LTQ07';
    END IF;

    IF p_bypass_quiz THEN
        INSERT INTO public.bypass_attempt_answers (
            attempt_id,
            source_question_id,
            selected_option_id,
            is_correct
        )
        VALUES (p_attempt_id, p_question_id, p_selected_option_id, v_correct)
        ON CONFLICT (attempt_id, source_question_id) DO UPDATE
            SET selected_option_id = EXCLUDED.selected_option_id,
                is_correct = EXCLUDED.is_correct,
                answered_at = CURRENT_TIMESTAMP;
    ELSE
        INSERT INTO public.attempt_answers (
            attempt_id,
            question_id,
            selected_option_id,
            is_correct
        )
        VALUES (p_attempt_id, p_question_id, p_selected_option_id, v_correct)
        ON CONFLICT (attempt_id, question_id) DO UPDATE
            SET selected_option_id = EXCLUDED.selected_option_id,
                is_correct = EXCLUDED.is_correct,
                answered_at = CURRENT_TIMESTAMP;
    END IF;

    attempt_id := p_attempt_id;
    question_id := p_question_id;
    is_correct := v_correct;
    RETURN NEXT;
    RETURN;

EXCEPTION
    WHEN OTHERS THEN
        IF SQLSTATE IN ('LTQ07', 'LTQ01') THEN
            RAISE;
        END IF;
        RAISE LOG 'sp_answer_quiz_question unexpected sqlstate=%: %', SQLSTATE, SQLERRM;
        RAISE EXCEPTION 'LT500: Unexpected database error while saving the answer: %', SQLERRM
            USING ERRCODE = 'LT500';
END;
$$;


