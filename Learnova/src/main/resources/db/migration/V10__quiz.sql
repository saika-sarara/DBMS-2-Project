-- =========================================================
-- V10: Quiz engine
--
-- All schema for the quiz feature in one file:
--   * lesson quizzes, questions and options
--   * regular quiz attempts (per enrollment) with a random question
--     snapshot and per-question answers
--   * bypass quiz attempts (passing a prerequisite course quiz to
--     satisfy that prerequisite without completing the course)
--   * quiz_submissions -- a history of graded attempts per user/quiz
--   * sp_start_quiz_attempt / sp_start_bypass_attempt /
--     sp_submit_quiz_attempt -- the grading flow
--   * vw_quiz_public -- sanitized questions/options for taking a quiz
--   * quiz indexes + demo seed quizzes
--
-- A passed bypass attempt inserts a row into public.course_bypasses,
-- which satisfies the prerequisite (V9) and fires the V9
-- trg_unlock_course_after_bypass trigger that unlocks course content.
-- =========================================================

-- =========================================================
-- 1. Quiz content
-- =========================================================

CREATE TABLE public.quizzes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    lesson_id            BIGINT NOT NULL,
    title                VARCHAR(255) NOT NULL,
    passing_score        NUMERIC(5,2) NOT NULL DEFAULT 60.00,
    questions_per_attempt INTEGER NOT NULL DEFAULT 5,
    daily_attempt_limit  INTEGER NOT NULL DEFAULT 3,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_quizzes
        PRIMARY KEY (id),

    CONSTRAINT uq_quizzes_lesson
        UNIQUE (lesson_id),

    CONSTRAINT fk_quizzes_lesson
        FOREIGN KEY (lesson_id)
        REFERENCES public.lessons (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_quizzes_title_not_blank
        CHECK (btrim(title) <> ''),

    CONSTRAINT chk_quizzes_passing_score
        CHECK (passing_score >= 0 AND passing_score <= 100),

    CONSTRAINT chk_quizzes_questions_per_attempt
        CHECK (questions_per_attempt > 0),

    CONSTRAINT chk_quizzes_daily_attempt_limit
        CHECK (daily_attempt_limit >= 1)
);

CREATE TRIGGER trg_quizzes_set_updated_at
BEFORE UPDATE ON public.quizzes
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE public.quiz_questions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    quiz_id        BIGINT NOT NULL,
    question_text  TEXT NOT NULL,
    sequence_order INTEGER NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_quiz_questions
        PRIMARY KEY (id),

    CONSTRAINT uq_quiz_questions_quiz_sequence
        UNIQUE (quiz_id, sequence_order),

    CONSTRAINT fk_quiz_questions_quiz
        FOREIGN KEY (quiz_id)
        REFERENCES public.quizzes (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_quiz_questions_text_not_blank
        CHECK (btrim(question_text) <> '')
);

CREATE TRIGGER trg_quiz_questions_set_updated_at
BEFORE UPDATE ON public.quiz_questions
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE public.quiz_options (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    question_id  BIGINT NOT NULL,
    option_label VARCHAR(5) NOT NULL,
    option_text  TEXT NOT NULL,
    is_correct   BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_quiz_options
        PRIMARY KEY (id),

    CONSTRAINT uq_quiz_options_question_label
        UNIQUE (question_id, option_label),

    CONSTRAINT fk_quiz_options_question
        FOREIGN KEY (question_id)
        REFERENCES public.quiz_questions (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_quiz_options_label_not_blank
        CHECK (btrim(option_label) <> ''),

    CONSTRAINT chk_quiz_options_text_not_blank
        CHECK (btrim(option_text) <> '')
);


-- =========================================================
-- 2. Regular quiz attempts (per enrollment)
-- =========================================================

