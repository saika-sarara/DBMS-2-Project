-- =========================================================
-- 3. Bypass quiz attempts
-- =========================================================

-- A bypass attempt lets a student pass the quiz of a prerequisite
-- course to satisfy that prerequisite without completing the course.
-- A passing attempt writes a course_bypasses row for
-- (user, target_course, prerequisite_course).
CREATE TABLE public.bypass_attempts (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id                BIGINT NOT NULL,
    target_course_id       BIGINT NOT NULL,
    prerequisite_course_id BIGINT NOT NULL,
    attempt_date           DATE NOT NULL DEFAULT CURRENT_DATE,
    attempt_no             INTEGER NOT NULL,
    status                 VARCHAR(20) NOT NULL DEFAULT 'in_progress',
    started_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_at           TIMESTAMPTZ,
    score_pct              NUMERIC(5,2),
    passed                 BOOLEAN,

    CONSTRAINT pk_bypass_attempts
        PRIMARY KEY (id),

    CONSTRAINT uq_bypass_attempts_user_target_prereq_date_no
        UNIQUE (user_id, target_course_id, prerequisite_course_id, attempt_date, attempt_no),

    CONSTRAINT fk_bypass_attempts_user
        FOREIGN KEY (user_id)
        REFERENCES public.users (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_bypass_attempts_target
        FOREIGN KEY (target_course_id)
        REFERENCES public.courses (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_bypass_attempts_prerequisite
        FOREIGN KEY (prerequisite_course_id)
        REFERENCES public.courses (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_bypass_attempts_status
        CHECK (status IN ('in_progress', 'submitted')),

    CONSTRAINT chk_bypass_attempts_score
        CHECK (score_pct IS NULL OR (score_pct >= 0 AND score_pct <= 100))
);

CREATE TABLE public.bypass_attempt_questions (
    attempt_id         BIGINT NOT NULL,
