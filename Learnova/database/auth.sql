-- =========================================================
-- Role-check helpers (used across every module)
-- =========================================================

CREATE OR REPLACE FUNCTION public.fn_user_has_role(
    p_user_id   BIGINT,
    p_role_name VARCHAR
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.user_roles ur
        JOIN public.roles r ON r.id = ur.role_id
        WHERE ur.user_id = p_user_id
          AND r.name = UPPER(BTRIM(p_role_name))
    );
$$;

CREATE OR REPLACE FUNCTION public.fn_user_is_instructor_or_admin(p_user_id BIGINT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
    SELECT
        public.fn_user_has_role(p_user_id, 'INSTRUCTOR')
        OR public.fn_user_has_role(p_user_id, 'ADMIN');
$$;
